#!/usr/bin/env python3
"""Maintain and enforce the reviewed Flake8 ratchet baseline."""

from __future__ import annotations

import argparse
import importlib.metadata
import os
import subprocess
import sys
from collections import Counter
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
BASELINE_PATH = BACKEND_DIR / "flake8-baseline.txt"
SOURCE_PATHS = ("src",)
REQUIRED_VERSIONS = {
    "flake8": "7.3.0",
    "pycodestyle": "2.14.0",
    "pyflakes": "3.4.0",
}


def verify_toolchain() -> None:
    """Refuse to compare results produced by an unreviewed analyzer toolchain."""
    mismatches = []
    for package, expected in REQUIRED_VERSIONS.items():
        try:
            actual = importlib.metadata.version(package)
        except importlib.metadata.PackageNotFoundError:
            actual = "not installed"
        if actual != expected:
            mismatches.append(f"{package}: expected {expected}, found {actual}")

    if mismatches:
        raise SystemExit("Flake8 baseline toolchain mismatch:\n" + "\n".join(mismatches))


def read_baseline() -> list[str]:
    """Load the reviewed findings without treating comments as findings."""
    return [
        line for line in BASELINE_PATH.read_text(encoding="utf-8").splitlines() if line and not line.startswith("#")
    ]


def run_flake8() -> subprocess.CompletedProcess[str]:
    """Run Flake8 deterministically from the backend directory."""
    env = {**os.environ, "PYTHONHASHSEED": "0"}
    return subprocess.run(
        [
            sys.executable,
            "-m",
            "flake8",
            *SOURCE_PATHS,
            "--max-line-length=120",
            "--exclude=__pycache__,migrations",
            "--ignore=E203,W503",
        ],
        cwd=BACKEND_DIR,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )


def current_findings() -> list[str]:
    """Return current Flake8 findings for the configured CI scope."""
    result = run_flake8()
    combined_output = result.stdout + result.stderr

    if result.returncode not in (0, 1):
        print(combined_output, end="", file=sys.stderr)
        raise SystemExit(f"Flake8 failed to execute (exit {result.returncode}).")

    return sorted(line for line in combined_output.splitlines() if line)


def write_baseline(findings: list[str]) -> None:
    """Write a reviewed baseline generated from the same command used by CI."""
    toolchain = ", ".join(f"{package} {version}" for package, version in REQUIRED_VERSIONS.items())
    body = "\n".join(findings)
    BASELINE_PATH.write_text(
        "\n".join(
            [
                "# Existing Flake8 findings for the full-backend lint migration policy.",
                "# Generated by scripts/flake8_baseline.py update; do not edit findings by hand.",
                f"# Scope: {', '.join(SOURCE_PATHS)}.",
                f"# Toolchain: {toolchain}.",
                "# Removals pass; additions or changed findings fail.",
                body,
                "",
            ]
        ),
        encoding="utf-8",
    )


def check() -> int:
    """Allow removal of debt, but reject every new or changed finding."""
    verify_toolchain()
    baseline = read_baseline()
    current = current_findings()

    new_findings = list((Counter(current) - Counter(baseline)).elements())
    if new_findings:
        print("New or changed Flake8 findings:", file=sys.stderr)
        print("\n".join(sorted(new_findings)), file=sys.stderr)
        print(
            f"Flake8 ratchet failed: {len(baseline)} baseline findings, "
            f"{len(current)} current findings, {len(new_findings)} new or changed.",
            file=sys.stderr,
        )
        return 1

    print(
        f"Flake8 ratchet passed: {len(baseline)} baseline findings, "
        f"{len(current)} current findings, 0 new or changed."
    )
    return 0


def update() -> int:
    """Regenerate the baseline from the exact Flake8 scope enforced by CI."""
    verify_toolchain()
    findings = current_findings()
    write_baseline(findings)
    print(f"Wrote {len(findings)} Flake8 findings to {BASELINE_PATH.relative_to(BACKEND_DIR)}.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("check", "update"))
    args = parser.parse_args()
    if args.command == "update":
        return update()
    return check()


if __name__ == "__main__":
    raise SystemExit(main())

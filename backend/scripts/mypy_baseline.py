#!/usr/bin/env python3
"""Maintain and enforce the reviewed MyPy ratchet baseline."""

from __future__ import annotations

import argparse
import importlib.metadata
import os
import subprocess
import sys
from collections import Counter
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
BASELINE_PATH = BACKEND_DIR / "mypy-baseline.txt"
CONFIG_PATH = BACKEND_DIR / "mypy-precommit.ini"
SOURCE_PATHS = ("src",)
REQUIRED_VERSIONS = {
    "mypy": "2.3.0",
    "django-stubs": "6.0.7",
    "djangorestframework-stubs": "3.17.0",
}


def error_lines(output: str) -> list[str]:
    """Return stable MyPy error fingerprints, excluding notes and summaries."""
    return sorted(line for line in output.splitlines() if ": error: " in line)


def verify_toolchain() -> None:
    """Refuse to compare results produced by an unreviewed analyzer toolchain."""
    mismatches = []
    for package, expected in REQUIRED_VERSIONS.items():
        try:
            actual = importlib.metadata.version(package)
        except importlib.metadata.PackageNotFoundError:
            actual = "not installed"
        if actual != expected:
            mismatches.append(f"{package}: expected {expected}, found {actual}")

    if mismatches:
        raise SystemExit("MyPy baseline toolchain mismatch:\n" + "\n".join(mismatches))


def read_baseline() -> list[str]:
    """Load the reviewed findings without treating comments as findings."""
    return [
        line for line in BASELINE_PATH.read_text(encoding="utf-8").splitlines() if line and not line.startswith("#")
    ]


def run_mypy() -> subprocess.CompletedProcess[str]:
    """Run MyPy deterministically from the backend directory."""
    env = {**os.environ, "PYTHONHASHSEED": "0"}
    return subprocess.run(
        [
            sys.executable,
            "-m",
            "mypy",
            "--config-file",
            str(CONFIG_PATH),
            "--no-incremental",
            "--cache-dir",
            os.devnull,
            "--show-error-codes",
            "--no-error-summary",
            *SOURCE_PATHS,
        ],
        cwd=BACKEND_DIR,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )


def current_findings() -> list[str]:
    """Return the current analyzer findings for the configured pre-commit scope."""
    result = run_mypy()
    combined_output = result.stdout + result.stderr
    current = error_lines(combined_output)

    if result.returncode not in (0, 1):
        print(combined_output, end="", file=sys.stderr)
        raise SystemExit(f"MyPy failed to execute (exit {result.returncode}).")

    return current


def write_baseline(findings: list[str]) -> None:
    """Write a reviewed baseline generated from the same command used by the hook."""
    toolchain = ", ".join(f"{package} {version}" for package, version in REQUIRED_VERSIONS.items())
    body = "\n".join(findings)
    BASELINE_PATH.write_text(
        "\n".join(
            [
                "# Existing MyPy findings for the non-strict migration policy in mypy-precommit.ini.",
                "# Generated by scripts/mypy_baseline.py update; do not edit findings by hand.",
                f"# Scope: {', '.join(SOURCE_PATHS)}.",
                f"# Toolchain: {toolchain}.",
                "# Removals pass; additions or changed findings fail.",
                body,
                "",
            ]
        ),
        encoding="utf-8",
    )


def check() -> int:
    """Allow removal of debt, but reject every new or changed finding."""
    verify_toolchain()
    baseline = read_baseline()
    current = current_findings()

    new_findings = list((Counter(current) - Counter(baseline)).elements())
    if new_findings:
        print("New or changed MyPy findings:", file=sys.stderr)
        print("\n".join(sorted(new_findings)), file=sys.stderr)
        print(
            f"MyPy ratchet failed: {len(baseline)} baseline findings, "
            f"{len(current)} current findings, {len(new_findings)} new or changed.",
            file=sys.stderr,
        )
        return 1

    print(
        f"MyPy ratchet passed: {len(baseline)} baseline findings, "
        f"{len(current)} current findings, 0 new or changed."
    )
    return 0


def update() -> int:
    """Regenerate the baseline from the exact MyPy scope enforced by pre-commit."""
    verify_toolchain()
    findings = current_findings()
    write_baseline(findings)
    print(f"Wrote {len(findings)} MyPy findings to {BASELINE_PATH.relative_to(BACKEND_DIR)}.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("check", "update"))
    args = parser.parse_args()
    if args.command == "update":
        return update()
    return check()


if __name__ == "__main__":
    raise SystemExit(main())
